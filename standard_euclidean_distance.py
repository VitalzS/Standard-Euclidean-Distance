import math

def euclidean_distance(p1, p2):
    """Calculate Euclidean distance between two points."""
    return math.sqrt(sum((a - b) ** 2 for a, b in zip(p1, p2)))

def read_points_from_file(filename):
    """Reads points from a text file, expecting one point (x, y) per line or multiple points on a single line."""
    points = []
    try:
        with open(filename, 'r') as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue

                # Remove outer brackets or parentheses if present, e.g., [{x, y}, {x, y}] or [(x, y), (x, y)]
                if (line.startswith('[') and line.endswith(']')) or \
                   (line.startswith('(') and line.endswith(')')):
                    line = line[1:-1] # Remove outer-most pair

                # Normalize point separators: replace '), (' and '),(' with a single unique separator
                # Also handle '}, {' for the new format.
                # This ensures consistent splitting regardless of spacing variations
                normalized_line = line.replace('), (', ';').replace('),(', ';')
                normalized_line = normalized_line.replace('}, {', ';').replace('},{', ';')

                # Split the line into individual point representations
                # If there are no separators, this will yield a single string
                point_strings = [s.strip() for s in normalized_line.split(';')]

                for ps in point_strings:
                    if not ps:
                        continue

                    # Remove leading/trailing parentheses or curly braces from each individual point string
                    ps = ps.strip('()')
                    ps = ps.strip('{}')

                    coords_str = ps.split(',')
                    if len(coords_str) == 2:
                        try:
                            x = float(coords_str[0].strip())
                            y = float(coords_str[1].strip())
                            points.append((x, y))
                        except ValueError:
                            print(f"Warning: Could not parse coordinates from point string: '{ps}' in line: '{line}'")
                    else:
                        print(f"Warning: Invalid point format: '{ps}' in line: '{line}'")
    except FileNotFoundError:
        raise FileNotFoundError(f"The file '{filename}' was not found. Please upload it to your Colab environment.")
    return points


def closest_pair(points):
    points_x = sorted(points, key=lambda p: p[0])
    points_y = sorted(points, key=lambda p: p[1])

    min_dist = closest_pair_recursive(points_x, points_y)
    return round(min_dist, 3)


def closest_pair_recursive(px, py):
    n = len(px)

    if n <= 3:
        min_dist = float('inf')
        for i in range(n):
            for j in range(i + 1, n):
                min_dist = min(
                    min_dist,
                    euclidean_distance(px[i], px[j])
                )
        return min_dist

    mid = n // 2
    midpoint = px[mid][0]

    left_x = px[:mid]
    right_x = px[mid:]

    left_y = []
    right_y = []

    for p in py:
        if p[0] <= midpoint:
            left_y.append(p)
        else:
            right_y.append(p)

    dl = closest_pair_recursive(left_x, left_y)
    dr = closest_pair_recursive(right_x, right_y)

    d = min(dl, dr)

    strip = [p for p in py if abs(p[0] - midpoint) < d]

    for i in range(len(strip)):
        for j in range(i + 1, min(i + 8, len(strip))):
            d = min(
                d,
                euclidean_distance(strip[i], strip[j])
            )


    return d

